'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const folder = fs.mkdtempSync(path.join(os.tmpdir(), 'tene-delivery-progress-'));
process.env.NODE_ENV = 'test';
process.env.JWT_SECRET = 'delivery-progress-local-test';
process.env.BCRYPT_ROUNDS = '4';
process.env.DB_PATH = path.join(folder, 'test.db');
process.env.BACKUP_DIR = path.join(folder, 'backups');
const { db, server, closeServer } = require('../server');
const { hashPin } = require('../auth-core');
const { buildDeliveryCertificateProgress, remainingDeliveryItems } = require('../services/deliveryCertificateProgress');

test('source snapshots are repeatable, stale-safe, and independent of corrected item statuses', async t => {
  db.prepare("INSERT INTO users (username,display_name,role,pin_hash,active,password_changed_at) VALUES ('shipment-office','Office','office',?,1,?)").run(hashPin('1234',4), new Date().toISOString());
  await new Promise(resolve => server.listen(0,'127.0.0.1',resolve));
  t.after(async () => { await new Promise(resolve => closeServer(resolve)); db.close(); fs.rmSync(folder,{ recursive:true,force:true }); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const login = await fetch(base + '/api/auth/login', { method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({username:'shipment-office',pin:'1234'}) });
  assert.equal(login.status,200);
  const headers = { Authorization:'Bearer ' + (await login.json()).access_token,'Content-Type':'application/json' };
  const get = url => fetch(base + '/api' + url,{headers});
  const patch = (id,body) => fetch(base + `/api/items/${id}/status`,{method:'PATCH',headers,body:JSON.stringify(body)});
  const customer = db.prepare("INSERT INTO customers (name) VALUES ('TEST only')").run().lastInsertRowid;
  const order = db.prepare("INSERT INTO orders (order_num,customer_id,status) VALUES ('TEST-PARTIAL',?,'בייצור')").run(customer).lastInsertRowid;
  const pallet = db.prepare('INSERT INTO pallets (order_id,pallet_num) VALUES (?,1)').run(order).lastInsertRowid;
  const insert = db.prepare("INSERT INTO items (pallet_id,order_id,shape_name,quantity,diameter,total_length_mm,total_weight,segments,status) VALUES (?,?,'מוט מכופף',?,12,2000,?,? ,?)");
  const one = insert.run(pallet,order,10,20,'[{"length_mm":1000,"angle_deg":90},{"length_mm":1000,"angle_deg":0}]','הועמס').lastInsertRowid;
  const two = insert.run(pallet,order,5,10,'[]','סופק').lastInsertRowid;
  const three = insert.run(pallet,order,20,40,'[]','בייצור').lastInsertRowid;
  const endpoint = `/orders/${order}/delivery-certificate`;
  assert.equal((await get(endpoint+'?certificate_mode=source')).status,409,'original requires fresh preview');
  const preview = await (await get(endpoint+'-preview')).json();
  assert.equal(preview.loaded_item_count,1);
  assert.equal(preview.total_item_count,3);
  assert.equal(preview.remaining_item_count,2);
  assert.equal(preview.shipped_unit_count,5);
  const draft = await get(endpoint+'?certificate_mode=draft');
  assert.equal(draft.status,200);
  assert.equal(db.prepare('SELECT COUNT(*) n FROM delivery_notes').get().n,0);
  assert.equal(db.prepare('SELECT status FROM items WHERE id=?').get(one).status,'הועמס');
  assert.equal((await get(endpoint+'?item_status=סופק')).status,400,'a filter cannot re-send delivered items');
  const sourceUrl = endpoint + '?certificate_mode=source&issue_key=' + preview.issue_key + '&selection_fingerprint=' + preview.selection_fingerprint;
  const source = await get(sourceUrl);
  assert.equal(source.status,200,await source.clone().text());
  const html = await source.text();
  assert.match(html,/1 מתוך 3 פריטים/);
  assert.equal(db.prepare('SELECT status FROM items WHERE id=?').get(one).status,'נשלח');
  const note = db.prepare('SELECT * FROM delivery_notes WHERE order_id=?').get(order);
  assert.equal(JSON.parse(note.items_json)[0].quantity,10);
  assert.equal((await get(sourceUrl)).status,200,'same issuance is reprint, not new departure');
  assert.equal(db.prepare('SELECT COUNT(*) n FROM delivery_notes').get().n,1);
  assert.equal((await patch(one,{status:'הושלם'})).status,409,'rollback requires reason');
  const corrected = await patch(one,{status:'הושלם',correction_reason:'תיקון תצוגת סטטוס בלבד'});
  assert.equal(corrected.status,200,await corrected.clone().text());
  assert.equal(db.prepare("SELECT COUNT(*) n FROM audit_log WHERE action='item_status_correction'").get().n,1);
  assert.equal((await get(endpoint+`?note_id=${note.id}`)).status,200,'saved certificate can be reopened after rollback');
  const after = await (await get(`/orders/${order}`)).json();
  assert.equal(after.delivery_progress.shipped_item_count,2,'ledger survives rollback');
  assert.equal(after.delivery_progress.remaining_item_count,1);
  assert.equal(after.delivery_progress.loaded_item_count,0);
  assert.equal(after.pallets[0].items.find(i=>i.id===Number(three)).quantity,20,'unshipped row untouched');
  const advanced = await patch(three,{status:'סופק'});
  assert.equal(advanced.status,200,await advanced.clone().text());
  const completed = db.prepare('SELECT * FROM items WHERE id=?').get(three);
  assert.equal(completed.produced_qty,20,'later status confirms production quantity');
  assert.ok(completed.started_at && completed.completed_at);
  assert.equal((await patch(three,{status:'בייצור',correction_reason:'בדיקת תיקון למצב קודם'})).status,200,'backward to production works');
  assert.equal((await (await get(`/orders/${order}`)).json()).delivery_progress.remaining_item_count,0,'old manual sent status survives its audited rollback');

  // A warehouse package snapshot can represent only part of a row.
  const partialOrder = db.prepare("INSERT INTO orders (order_num,customer_id,status) VALUES ('TEST-PACK',?,'אספקה חלקית')").run(customer).lastInsertRowid;
  const partialPallet = db.prepare('INSERT INTO pallets (order_id,pallet_num) VALUES (?,1)').run(partialOrder).lastInsertRowid;
  const partial = insert.run(partialPallet,partialOrder,10,20,'[]','הועמס').lastInsertRowid;
  db.prepare('INSERT INTO delivery_notes (note_num,order_id,items_json,packages_json) VALUES (?,?,?,?)').run('TEST-PACK-NOTE',partialOrder,JSON.stringify([{id:partial,quantity:10}]),JSON.stringify([{item_ids:[partial],quantity:4,weight:8}]));
  const raw = db.prepare('SELECT * FROM items WHERE id=?').get(partial);
  const progress = buildDeliveryCertificateProgress(db,partialOrder,[raw]);
  assert.equal(progress.remaining_unit_count,6);
  assert.equal(progress.partially_shipped_item_count,1);
  const selected = remainingDeliveryItems([raw],progress,true);
  assert.equal(selected[0].quantity,6);
  assert.equal(selected[0].total_weight,12);
  assert.equal(raw.quantity,10,'read projection never changes source row');
  const oldPreview = await (await get(`/orders/${partialOrder}/delivery-certificate-preview`)).json();
  db.prepare("UPDATE items SET status='הושלם' WHERE id=?").run(partial);
  assert.equal((await get(`/orders/${partialOrder}/delivery-certificate?certificate_mode=source&issue_key=${oldPreview.issue_key}&selection_fingerprint=${oldPreview.selection_fingerprint}`)).status,409,'changed loading rejected');
  assert.equal(db.prepare('SELECT COUNT(*) n FROM delivery_notes WHERE order_id=?').get(partialOrder).n,1);
  const completionOrder = db.prepare("INSERT INTO orders (order_num,customer_id,status) VALUES ('TEST-ALL-STAGES',?,'בייצור')").run(customer).lastInsertRowid;
  const completionPallet = db.prepare('INSERT INTO pallets (order_id,pallet_num) VALUES (?,1)').run(completionOrder).lastInsertRowid;
  const advancedRow = insert.run(completionPallet,completionOrder,3,6,'[]','סופק').lastInsertRowid;
  const lastRow = insert.run(completionPallet,completionOrder,4,8,'[]','בייצור').lastInsertRowid;
  assert.equal((await patch(lastRow,{status:'הושלם'})).status,200);
  assert.equal(db.prepare('SELECT status FROM orders WHERE id=?').get(completionOrder).status,'הושלם – ממתין לאיסוף','already supplied row counts as produced');
  assert.equal((await patch(lastRow,{status:'בייצור',correction_reason:'חזרה להשלמת עבודה'})).status,200);
  assert.equal(db.prepare('SELECT status FROM orders WHERE id=?').get(completionOrder).status,'בייצור','rollback restores the work queue');
  assert.ok(advancedRow > 0);
  assert.equal(two > 0,true);
});
